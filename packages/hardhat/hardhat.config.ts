import { defineConfig, overrideTask } from "hardhat/config";
import toolbox from "@nomicfoundation/hardhat-toolbox-mocha-ethers";
import deploy from "hardhat-deploy";
import { readFileSync, writeFileSync } from "node:fs";

export default defineConfig({
  plugins: [toolbox, deploy],
  solidity: "0.8.30",
  generateTypedArtifacts: { destinations: [{ folder: "./generated", mode: "typescript" }] },
  networks: {
    hardhat: { type: "edr-simulated", chainId: 31337 },
    localhost: { type: "http", url: "http://127.0.0.1:8545", chainId: 31337 },
  },
  tasks: [overrideTask("deploy").setInlineAction(async (args, hre, runSuper) => {
    await runSuper(args);
    const dir = "./deployments/localhost";
    const { address, abi } = JSON.parse(readFileSync(dir + "/CertificateRegistry.json", "utf8"));
    const chain = JSON.parse(readFileSync(dir + "/.chain", "utf8"));
    if (Number(chain.chainId) !== 31337) throw new Error("Unexpected chain ID");
    const contracts = { 31337: { CertificateRegistry: { address, abi } } };
    writeFileSync("../nextjs/contracts/deployedContracts.ts",
      "// Generated by the local deployment task.\nexport default " + JSON.stringify(contracts, null, 2) + " as const;\n");
  }).build()],
});
